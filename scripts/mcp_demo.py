"""Drive the MCP server over stdio exactly like an agent would, and write
examples/agent_queries.md with the REAL outputs.

WHY: proves the server works end to end through the MCP protocol (not just as
Python functions) and keeps the examples honest - they are regenerated, never typed.
Run: uv run python scripts/mcp_demo.py
"""
from __future__ import annotations

import asyncio
import json
import sys
from pathlib import Path

from mcp import ClientSession, StdioServerParameters
from mcp.client.stdio import stdio_client

ROOT = Path(__file__).resolve().parents[1]

EXAMPLES = [
    ("What data is available?", "list_tables", {}),
    ("Which governed metrics can I ask for?", "list_metrics", {}),
    ("How fast did Florida's population grow between the 2015-2019 and 2020-2024 ACS?",
     "get_metric", {"name": "population_growth", "group_by": "state"}),
    ("What is the median household income in Miami-Dade County (ACS 2024)?",
     "get_metric", {"name": "median_household_income", "group_by": "county", "year": 2024, "county": "Miami-Dade"}),
    ("Florida's official median age in each loaded vintage?",
     "get_metric", {"name": "median_age", "group_by": "state"}),
    ("Which 5 counties grew fastest from ACS 2019 to ACS 2024?",
     "run_query", {"sql": "select county_name, total_population_start, total_population_end, "
                          "round(total_population_growth, 4) as growth from main.fct_county_growth "
                          "where start_year = 2019 and end_year = 2024 order by total_population_growth desc limit 5"}),
    ("Which 5 counties have the highest Hispanic share in ACS 2024?",
     "run_query", {"sql": "select county_name, pop_hispanic, pop_hispanic_moe, round(pct_hispanic, 4) as pct_hispanic "
                          "from main.fct_county_demographics where acs_year = 2024 order by pct_hispanic desc limit 5"}),
    ("Do county populations add up to the official state total?",
     "run_query", {"sql": "select acs_year, total_population, county_sum_total_population, county_count "
                          "from main.fct_state_demographics order by acs_year"}),
    ("What columns does fct_county_growth have?", "describe_table", {"table": "fct_county_growth"}),
    ("(Safety) Can an agent delete data?", "run_query", {"sql": "drop table main.dim_county"}),
]


def _fmt(result) -> str:
    if result.isError:
        return "ERROR: " + " ".join(c.text for c in result.content if hasattr(c, "text"))
    if result.structuredContent is not None:
        data = result.structuredContent
        data = data.get("result", data) if isinstance(data, dict) and set(data) == {"result"} else data
    else:
        data = [json.loads(c.text) for c in result.content]
        data = data[0] if len(data) == 1 else data
    return json.dumps(data, indent=2, default=str)


async def main() -> None:
    params = StdioServerParameters(command=sys.executable, args=["-m", "census_mcp.server"], cwd=str(ROOT))
    out = ["# Example agent queries\n",
           "Generated by `uv run python scripts/mcp_demo.py`, which launches the MCP server over **stdio** "
           "and calls its tools exactly as an agent would. Outputs below are the actual responses from the "
           "real Florida ACS data in `data/census.duckdb` (regenerate after re-ingesting). Current data: ACS 5-year 2019 and 2024, loaded with `--source summary_file` (official Census ACS Summary File) because the API key was not accepted at build time.\n"]
    async with stdio_client(params) as (r, w):
        async with ClientSession(r, w) as s:
            await s.initialize()
            tools = await s.list_tools()
            out.append("Tools advertised by the server: " + ", ".join(f"`{t.name}`" for t in tools.tools) + "\n")
            for i, (q, tool, args) in enumerate(EXAMPLES, 1):
                res = await s.call_tool(tool, args)
                text = _fmt(res)
                print(f"[{i}] {tool}: {'error' if res.isError else 'ok'}", file=sys.stderr)
                out += [f"## {i}. {q}\n", f"**Tool call:** `{tool}`\n", "```json\n" + json.dumps(args, indent=2) + "\n```\n",
                        "**Actual output:**\n", "```json\n" + text + "\n```\n"]
    (ROOT / "examples" / "agent_queries.md").write_text("\n".join(out))


if __name__ == "__main__":
    asyncio.run(main())
